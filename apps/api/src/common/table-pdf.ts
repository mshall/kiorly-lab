import PDFDocument from "pdfkit";

export interface TablePdfInput {
  title: string;
  subtitle?: string;
  columns: { key: string; label: string; width?: number; align?: "left" | "right" }[];
  rows: Record<string, unknown>[];
  totals?: Record<string, unknown>;
  footer?: string;
  landscape?: boolean;
}

const latin = (s: string) => s.replace(/[^\x20-\x7e]/g, "?");
const fmt = (v: unknown) => (v == null ? "" : typeof v === "number" ? (Number.isInteger(v) ? String(v) : v.toFixed(2)) : v instanceof Date ? v.toISOString().slice(0, 10) : String(v));

/** Generic printable table (CSV companion): header, striped rows, totals line, page numbers. Latin text only (exports for accountants). */
export function renderTablePdf(t: TablePdfInput): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", layout: t.landscape ? "landscape" : "portrait", margin: 40, bufferPages: true, info: { Title: t.title, Producer: "Kiorly Lab" } });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);
    const L = doc.page.margins.left;
    const W = doc.page.width - L - doc.page.margins.right;
    const auto = t.columns.filter((c) => !c.width).length || 1;
    const fixed = t.columns.reduce((a, c) => a + (c.width ?? 0), 0);
    const widths = t.columns.map((c) => c.width ?? Math.max(40, (W - fixed) / auto));
    const scale = W / widths.reduce((a, b) => a + b, 0);
    const w = widths.map((x) => x * scale);
    const X = (i: number) => L + w.slice(0, i).reduce((a, b) => a + b, 0);
    doc.font("Helvetica-Bold").fontSize(15).fillColor("#3730A3").text(latin(t.title), L, doc.y);
    if (t.subtitle) doc.font("Helvetica").fontSize(9).fillColor("#6B7280").text(latin(t.subtitle));
    doc.moveDown(0.8);
    let y = doc.y;
    const head = () => {
      doc.rect(L, y - 3, W, 16).fill("#EEF2FF");
      doc.fillColor("#1E1B4B").font("Helvetica-Bold").fontSize(8);
      t.columns.forEach((c, i) => doc.text(latin(c.label), X(i) + 3, y, { width: w[i]! - 6, align: c.align ?? "left", lineBreak: false, ellipsis: true }));
      y += 17;
    };
    head();
    t.rows.forEach((r, n) => {
      if (y > doc.page.height - 70) { doc.addPage(); y = doc.page.margins.top; head(); }
      if (n % 2) doc.rect(L, y - 2, W, 13).fill("#F9FAFB");
      doc.fillColor("#111827").font("Helvetica").fontSize(8);
      t.columns.forEach((c, i) => doc.text(latin(fmt(r[c.key])), X(i) + 3, y, { width: w[i]! - 6, align: c.align ?? "left", lineBreak: false, ellipsis: true }));
      y += 13;
    });
    if (t.totals) {
      if (y > doc.page.height - 70) { doc.addPage(); y = doc.page.margins.top; }
      doc.moveTo(L, y).lineTo(L + W, y).strokeColor("#3730A3").stroke();
      y += 4;
      doc.font("Helvetica-Bold").fontSize(8).fillColor("#111827");
      t.columns.forEach((c, i) => doc.text(latin(fmt(t.totals![c.key])), X(i) + 3, y, { width: w[i]! - 6, align: c.align ?? "left", lineBreak: false }));
    }
    const range = doc.bufferedPageRange();
    for (let i = 0; i < range.count; i++) {
      doc.switchToPage(i);
      const prev = doc.page.margins.bottom;
      doc.page.margins.bottom = 0;
      doc.font("Helvetica").fontSize(7).fillColor("#6B7280").text(latin(`${t.footer ?? "Generated by Kiorly Lab. For your accountant; not submitted to any authority."}   Page ${i + 1} of ${range.count}`), L, doc.page.height - 28, { width: W, align: "left", lineBreak: false });
      doc.page.margins.bottom = prev;
    }
    doc.end();
  });
}
